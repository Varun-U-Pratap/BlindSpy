"""Write the result tables from history.csv: Phase 2 -> reports/baseline_tables.md,
Phase 3 -> reports/phase3_tables.md (every table and threshold check).

Run scripts/export_history.py first. The report drafts and the E## entries quote these
tables, so no result is typed by hand.

Usage: uv run python scripts/results_tables.py [--phase 3|4]
"""

import argparse
import json

import pandas as pd

from blindspy import results as R
from blindspy.tracking import ROOT, load_yaml

OUT = ROOT / "reports" / "baseline_tables.md"
OUT3 = ROOT / "reports" / "phase3_tables.md"
OUT4 = ROOT / "reports" / "phase4_tables.md"


def storage(h: pd.DataFrame, runner: str, by_experiment: bool = False) -> tuple[pd.DataFrame, dict]:
    """Bytes in mlruns/<runner>/artifacts per run, grouped by model type (and experiment).
    The *_MB columns are MiB (2**20 bytes)."""
    art = ROOT / "mlruns" / runner / "artifacts"
    rows = []
    for _, r in h.iterrows():
        folder = art / r["run_id"]
        size = (
            sum(f.stat().st_size for f in folder.rglob("*") if f.is_file())
            if folder.exists()
            else 0
        )
        model_file = folder / "artifacts" / "model" / "model.joblib"
        rows.append({
            "kind": (f"{r['tags.experiment_id']} {r['params.model']}" if by_experiment
                     else f"{r['params.model']} ({r['tags.protocol']})"), "run_bytes": size,
            "model_file_bytes": model_file.stat().st_size if model_file.exists() else 0,
        })  # fmt: skip
    df = pd.DataFrame(rows).groupby("kind").agg(
        runs=("run_bytes", "size"), total_MB=("run_bytes", lambda s: s.sum() / 2**20),
        per_run_max_MB=("run_bytes", lambda s: s.max() / 2**20),
        model_file_max_MB=("model_file_bytes", lambda s: s.max() / 2**20),
    ).round(3).reset_index()  # fmt: skip
    total = {
        "artifacts_MB": round(
            sum(f.stat().st_size for f in art.rglob("*") if f.is_file()) / 2**20, 1
        ),
        "mlflow_db_MB": round((ROOT / "mlruns" / runner / "mlflow.db").stat().st_size / 2**20, 1),
    }
    return df, total


def main() -> None:
    base = load_yaml(ROOT / "configs" / "base.yaml")
    runner = base["official_runner"]
    h = R.load_history()
    b = R.baselines(h)
    bench = R.benchmark(h)
    paper = R.load_paper()
    raw = pd.read_csv(ROOT / "reports" / "history.csv", low_memory=False)
    names = set(b["run_name"]) | set(bench["run_name"])
    earlier = set(raw.loc[raw["run_name"].isin(names), "tags.git_commit"].str[:7]) - {
        c[:7] for c in set(b["tags.git_commit"]) | set(bench["tags.git_commit"])
    }
    commits = sorted(set(b["tags.git_commit"]) | set(bench["tags.git_commit"]))
    out = ["# Phase 2 baseline tables", "",
           "Generated by `scripts/results_tables.py` from `reports/history.csv`.",
"Do not edit by hand.",
           "Validation scores (holdout protocol: 70/15/15 split, seed 42, test set untouched) and",
           "the paper benchmark (10-fold CV on the whole file). Data version: "
           + ", ".join(sorted(set(b["tags.data_version"]))) + ".", "",
           f"- Baseline runs: {len(b)} (5 models x 16 task/timeout configs), "
           f"status FINISHED: {int((b['status'] == 'FINISHED').sum())}.",
           f"- Benchmark runs: {len(bench)} (2 algorithms x 16 files x 2 row sources).",
           "- Git commit(s) of these runs: " + ", ".join(c[:7] for c in commits) + ".",
           "- Earlier runs of the same configs (identical scores; kept in MLflow and in "
           "history.csv): " + ", ".join(sorted(earlier)) + "."]  # fmt: skip

    out += [
        "",
        "## Validation macro F1 (E01-E03)",
        "",
        R.md(R.score_grid(b, "metrics.val_f1_macro")),
    ]
    out += [
        "",
        "## 5-fold CV macro F1 on train, mean +- std",
        "",
        R.md(R.score_grid(b, "metrics.cv_f1_macro_mean", "metrics.cv_f1_macro_std")),
    ]
    for metric, title in [("metrics.val_accuracy", "Validation accuracy"),
                          ("metrics.val_balanced_accuracy", "Validation balanced accuracy"),
                          ("metrics.val_f1_weighted", "Validation weighted F1"),
                          ("metrics.gen_gap_f1_macro",
                           "Generalisation gap (CV - validation, macro F1)")]:  # fmt: skip
        out += ["", f"## {title}", "", R.md(R.score_grid(b, metric))]
    a1 = b[b["params.task"] == "A1"].sort_values(["params.model", "params.timeout"])
    out += ["", "## A1 validation ROC-AUC", "",
            R.md(pd.DataFrame({"model": a1["params.model"],
                               "timeout": a1["params.timeout"].astype(int),
                               "ROC-AUC": a1["metrics.val_roc_auc"].round(3)}))]  # fmt: skip

    out += [
        "",
        "## E01 check: accuracy = p, macro F1 = 2p / ((1 + p) k)",
        "",
        R.md(R.majority_check(b)),
    ]
    for m in ("tree", "knn", "logreg", "svm_rbf"):
        out += [
            "",
            f"## Per-class extremes and F1 gaps: {m} ({R.MODEL_EXP[m]})",
            "",
            R.md(R.class_extremes(b, m)),
        ]
    for m in ("tree", "knn", "logreg", "svm_rbf"):
        out += [
            "",
            f"## Top 5 confusion pairs (validation): {m} ({R.MODEL_EXP[m]})",
            "",
            R.md(R.confusion_pairs(b, m)),
        ]
    out += ["", "## Model complexity", "", R.md(R.complexity(b))]
    out += [
        "",
        "## Cost per model (over the 16 configs)",
        "",
        R.md(R.cost_table(b)),
        "",
        "Peak fit memory is measured with Python's tracemalloc, which counts NumPy arrays",
        "but not memory allocated inside compiled libraries (for example libsvm), so SVM",
        "memory is a lower bound. Training time comes from a fit without tracemalloc and",
        "peak memory from a separate fit of a clone. The first Phase 2 runs (commits",
        "1817c5a and 36c56a1) timed the fit with tracemalloc on, which slowed it (x1.05",
        "tree, x1.00 SVM, x1.19 Logistic Regression, x2.3 KNN in a recheck); all 144 configs",
        "were rerun from the fixed code (commit c450c3e) with identical scores, and these",
        "tables use the rerun. The first runs also logged process_max_rss_mb, a high-water",
        "mark of the whole batch process rather than a per-run figure; it is not used.",
    ]

    out += [
        "",
        "## Paper benchmark: A1 (paper Figure 2 values, read to +-0.01)",
        "",
        R.md(R.paper_a1(bench, paper)),
    ]
    for rows in ("published", "v1"):
        for task in R.CORE_TASKS:
            out += [
                "",
                f"## Paper benchmark per task: {task}, rows {rows} "
                "(10-fold precision and recall per class)",
                "",
                "Ours, with the paper's value in brackets where the paper gives one (C = read",
                "from a chart, +-0.01; T = stated in the text). The paper's Figure 3 per-class",
                "values for A2 and B can't be assigned to C4.5 or KNN, so they are not shown.",
                "",
                R.md(R.paper_task_table(bench, paper, task, rows)),
            ]
    out += [
        "",
        "## Paper benchmark: A2 and B (values stated in the paper's text)",
        "",
        "For averages the paper does not say whether it is a plain or a class-weighted mean",
        "(Weka prints the weighted one), so both are shown.",
        "",
        R.md(R.paper_text_values(bench, paper)),
    ]
    out += [
        "",
        "## Paper benchmark: duplicates (10-fold macro F1, published rows vs data v1)",
        "",
        R.md(R.dedup_effect(bench)),
        "",
        "## What the removed duplicates are (raw files)",
        "",
        "Share of removed rows whose features also occur with another label, and packets per",
        "flow. A1 120 s packet counts use its published (corrupt) flowPktsPerSecond.",
        "",
        R.md(R.duplicate_profile()),
    ]

    st, total = storage(pd.concat([b, bench]), runner)
    out += [
        "",
        "## Storage of these runs (mlruns/" + runner + ")",
        "",
        R.md(st),
        "",
        f"Whole store now: artifacts {total['artifacts_MB']} MB, "
        f"mlflow.db {total['mlflow_db_MB']} MB.",
    ]

    v = R.verdicts(b, bench, paper)
    out += [
        "",
        "## Threshold checks (pre-stated in E01-E03)",
        "",
        "```json",
        json.dumps(v, indent=1, default=lambda x: x.item()),
        "```",
        "",
    ]
    OUT.write_text("\n".join(out))
    print(f"Wrote {OUT.relative_to(ROOT)}")
    for k, x in v.items():
        print(
            k,
            "supported" if x["supported"] else "NOT supported",
            {a: c for a, c in x.items() if a != "supported"},
        )


def phase3() -> None:
    h = R.load_history()
    s = R.selection_runs(h)
    p3 = s[~s["tags.experiment_id"].isin(["E01", "E02", "E03"])]
    commits = sorted(set(p3["tags.git_commit"].str[:7]))
    out = ["# Phase 3 tables", "",
           "Generated by `scripts/results_tables.py --phase 3` from `reports/history.csv`.",
           "Do not edit by hand.", "",
           "Validation scores (holdout protocol: 70/15/15 split, seed 42, test set untouched).",
           f"Winner rule: a 15 s validation macro F1 at least {R.WINNER_MARGIN} above the task's",
           "current best -> rerun at 30, 60 and 120 s with the same settings. Optuna trial runs",
           "are excluded. Data version: " + ", ".join(sorted(set(p3["tags.data_version"])))
           + ".", "",
           f"- Phase 3 holdout runs: {len(p3)}, status FINISHED: "
           f"{int((p3['status'] == 'FINISHED').sum())}.",
           "- Git commit(s) of these runs: " + ", ".join(commits) + "."]  # fmt: skip
    runner = load_yaml(ROOT / "configs" / "base.yaml")["official_runner"]
    done = [e for e in R.SELECTION_EXPS[3:] if (s["tags.experiment_id"] == e).any()]
    for exp in done:
        out += ["", f"## Current best at 15 s after {exp}", "", R.md(R.current_best(s, exp))]
        out += ["", f"## {exp} at 15 s against the best run before it", "",
                R.md(R.screen(s, exp))]  # fmt: skip
        reruns = s[(s["tags.experiment_id"] == exp) & (s["params.timeout"] != 15)]
        for (label, task), _ in reruns.groupby(["label", "params.task"]):
            out += ["", f"## Winner rerun: {label}, {task}, every timeout", "",
                    R.md(R.timeout_table(s, label, task))]  # fmt: skip
        out += ["", f"## {exp} run details", "", R.md(R.run_details(s, exp))]
        if exp == "E06":
            out += ["", "## E07 scope: best 2 of RF / XGBoost / LightGBM per task, plus KNN",
                    "", R.md(R.e07_candidates(s))]  # fmt: skip
        if exp == "E10":
            out += ["", "## E10 task B: direct vs two-step (errors split at the VPN / non-VPN "
                    "line)", "", R.md(R.e10_table(s, runner))]  # fmt: skip
        if exp == "E08":
            out += ["", "## E08 balancing ladder (stop rule: a step runs only if every earlier "
                    "step helped)", "", R.md(R.e08_ladder(s, R.E08_BASE))]  # fmt: skip
        if exp in ("E07", "E17"):
            out += ["", f"## {exp} searches: size, chosen settings, tuned vs untuned", "",
                    R.md(R.e07_searches(s, exp))]  # fmt: skip
        if exp == "E04":
            out += ["", "## E04: columns RobustScaler leaves unscaled (training rows, after "
                    "the signed log)", "", R.md(R.robust_scaling_check())]  # fmt: skip
    out += [
        "",
        "## Final choice per task (highest validation macro F1, decided 28 Oct after "
        "E10; configs/final/<task>.yaml)",
        "",
        R.md(
            R.final_choice(s).drop(columns="run_id").round({"val macro F1": 4, "next best F1": 4})
        ),
    ]
    out += [
        "",
        "## Comparison set (best 15 s validation variant of each method type; "
        "configs/final/compare/)",
        "",
        R.md(R.comparison_set(s).drop(columns="run_id").round({"val macro F1": 4})),
    ]
    old = R.old_rule_choice(s)
    old["in comparison set"] = old["run"].isin(R.comparison_set(s)["run"])
    out += [
        "",
        "## What the superseded 28 Oct tie rule would pick (configs/final/old_rule/ "
        "where not in the comparison set)",
        "",
        R.md(old.drop(columns="run_id").round({"val macro F1": 4})),
    ]
    # every Phase 3 run with a model (selection and analysis experiments; trials save none)
    every = h[h["tags.experiment_id"].isin(["E04", "E05", "E06", "E07", "E08", "E09", "E10",
                                            "E13", "E14", "E16", "E17"])]  # fmt: skip
    if "tags.trial" in every.columns:
        every = every[every["tags.trial"].astype(str) != "True"]
    st, total = storage(every, runner, by_experiment=True)
    out += ["", f"## Storage of the Phase 3 runs (mlruns/{runner}, models saved with joblib "
            "compression level 3)", "", "Sizes in MiB (2**20 bytes). Optuna trial runs save no "
            "model and are not included.", "", R.md(st), "",
            f"Whole store now: artifacts {total['artifacts_MB']} MiB, "
            f"mlflow.db {total['mlflow_db_MB']} MiB."]  # fmt: skip
    v = R.phase3_verdicts(s, runner)
    if (h["tags.experiment_id"] == "E09").any():
        t9 = R.e09_table(h, s)
        out += ["", "## E09 feature-group ablation on the headline model per task (15 s, "
                "validation; \"all\" = the headline run)", "", R.md(t9)]  # fmt: skip
        v.update(R.e09_verdicts(t9))
    if (h["tags.experiment_id"] == "E16").any():
        out += [
            "",
            "## E16 Isnan et al. on the Kaggle CSV (data version kaggle-k1; test = the "
            "80/20 split's Kaggle test rows, not our v1 test set)",
            "",
            R.md(R.e16_table(h)),
        ]
        if R.e16_size_table(h).shape[0]:
            out += ["", "## E16 (d) training-size control (data version kaggle-k1; (a)'s forest "
                    "on the timeouts-mixed training rows cut to each per-timeout training size, "
                    "5 subsample seeds; scored on (a)'s test rows)", "",
                    R.md(R.e16_size_table(h))]  # fmt: skip
        v.update(R.e16_verdicts(h))
    if (h["tags.experiment_id"] == "E13").any():
        t13 = R.e13_table(h, s)
        out += [
            "",
            "## E13 learning curve on the headline model per task (15 s, validation; "
            "5 subsample seeds per fraction, 100% = the headline run)",
            "",
            R.md(t13),
        ]
        v.update(R.e13_verdicts(t13))
    if (h["tags.experiment_id"] == "E14").any():
        t14 = R.e14_table(h, s)
        out += ["", "## E14 split-seed stability on the headline model per task (10 resplits of "
                "train + validation, seeds 42-51; test rows untouched)", "", R.md(t14),
                "", "Mean validation confusion matrices over the 10 resplits: "
                "reports/e14_mean_confusion/<task>.csv."]  # fmt: skip
        folder = ROOT / "reports" / "e14_mean_confusion"
        folder.mkdir(exist_ok=True)
        for task in t14["task"]:
            R.e14_mean_confusion(h, task, runner).to_csv(folder / f"{task}.csv")
        v.update(R.e14_verdicts(t14))
    out += ["", "## Threshold checks (pre-stated in the E## files)", "", "```json",
            json.dumps(v, indent=1, default=lambda x: x.item()), "```", ""]  # fmt: skip
    OUT3.write_text("\n".join(out))
    print(f"Wrote {OUT3.relative_to(ROOT)}")
    for k, x in v.items():
        if "supported" in x:
            print(k, "supported" if x["supported"] else "NOT supported")
        else:  # a stop-and-ask check, not a hypothesis
            print(k, "TRIGGERED (ask the user)" if x["triggered"] else "not triggered")


def e12_sections(h, runner: str, name: str, protocol: str, root) -> tuple[list[str], dict]:
    """E12 tables from the final runs' saved predictions (also used on the rehearsal store)."""
    scores, draws = R.e12_scores(h, runner, name, protocol, root)
    tests = R.e12_tests(scores, draws)
    show = scores.drop(columns=[c for c in scores.columns if c.startswith("_")])
    head = show[show["role"] == "headline"]
    out = ["", f"## E12 headline models on the {name} rows (fit on train + validation; 95% "
           f"percentile intervals from {R.N_BOOT:,} stratified paired resamples, seed "
           f"{R.BOOT_SEED}; intervals are conditional on the test class counts)", "",
           R.md(head),
           "", f"## E12 all {len(show)} final models (headline, comparison set, old-rule picks), "
           f"{name} rows", "", R.md(show),
           "", f"## E12 the {len(tests)} paired tests on macro F1 (headline - other, two-sided "
           f"paired bootstrap, Holm over all {len(tests)} at {R.HOLM_ALPHA})", "",
           R.md(tests.assign(p=tests["p"].map(lambda x: f"{x:.4f}"),
                             **{"Holm p": tests["Holm p"].map(lambda x: f"{x:.4f}")}))]  # fmt: skip
    return out, R.e12_verdicts(scores, h)


def phase4() -> None:
    h = R.load_history()
    out = ["# Phase 4 tables", "",
           "Generated by `scripts/results_tables.py --phase 4` from `reports/history.csv`.",
           "Do not edit by hand.", ""]  # fmt: skip
    v = {}
    if (h["tags.experiment_id"] == "E15").any():
        t15 = R.e15_table(h)
        out += ["## E15 calibration of the headline models on validation (fitted on train; "
                "isotonic, shuffled 5-fold out-of-fold mapping, seed 42; ECE 15 bins)", "",
                "Adopted = uncalibrated ECE above 0.05 and isotonic ECE lower (rule fixed 31 Oct). "
                "Calibration changes only the reported confidence: the predicted class is always "
                "the uncalibrated model's.", "", R.md(t15),
                "", "Reliability diagrams: MLflow artifact calibration/reliability.png of each "
                "run; reports/figures/e15_reliability.png."]  # fmt: skip
        runner = load_yaml(ROOT / "configs" / "base.yaml")["official_runner"]
        R.e15_reliability_figure(h, runner, ROOT / "reports" / "figures" / "e15_reliability.png")
        v.update(R.e15_verdicts(h))
    if ((h["tags.experiment_id"] == "E12") & (h["tags.protocol"] == "final_test")).any():
        runner = load_yaml(ROOT / "configs" / "base.yaml")["official_runner"]
        out_e12, v12 = e12_sections(h, runner, "test", "final_test", ROOT)
        out += out_e12
        v.update(v12)
    out += ["", "## Threshold checks (pre-stated in the E## files)", "", "```json",
            json.dumps(v, indent=1, default=lambda x: x.item()), "```", ""]  # fmt: skip
    OUT4.write_text("\n".join(out))
    print(f"Wrote {OUT4.relative_to(ROOT)}")
    for k, x in v.items():
        if "supported" in x:
            print(k, "supported" if x["supported"] else "NOT supported")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", type=int, choices=[2, 3, 4], default=2)
    phase = ap.parse_args().phase
    {2: main, 3: phase3, 4: phase4}[phase]()
